"""
hand_angles_v2.py
=================
Thin adapter between `anatomical_angles_v12` (the ONE canonical angle module)
and the EKF / runner code, which works in flat numpy arrays and in the bone
NAMES that `calib_adapter.py` emits.

This file deliberately contains no angle mathematics. Every formula lives in
`anatomical_angles_v12`. If you find yourself adding a trig function here,
stop: two copies of the angle definition drifting apart has been the source of
every serious bug in this project.

WHAT IT ADAPTS
--------------
1. dict <-> array.  `compute_angles_v12` returns a dict of 25 names; the EKF
   state is a (21,) vector in `ARTICULATION_ANGLES` order.
2. bone-length KEYS.  `forward_kinematics_v12` wants
   {(parent_idx, child_idx): length}.  `calib_adapter.py` writes
   {"Middle_MCP-PIP": length}.  `as_bone_dict` accepts either, plus a plain
   (20,) array in `BONES` order.
3. units.  Calibration is in millimetres, MediaPipe world landmarks are in
   metres. v12 itself is unit-agnostic, so `scale` is applied here and nowhere
   else.  Set scale=1e-3 to feed mm calibration into a metre-based FK.

FAN ANGLES ARE NOT STATE
------------------------
`compute_angles` returns only the 21 articulation angles. The 4 fan angles are
near-constant within a subject and belong in calibration; get them with
`compute_fan` once, store them, and pass them to `forward_kinematics` via
`fan_angles=`. FK raises if it has neither a fan value in `angles` nor an
explicit `fan_angles` -- it will not silently reconstruct with zero spread.

ROUND-TRIP EXPECTATIONS  (read before interpreting the self-test)
-----------------------------------------------------------------
* Poses GENERATED by FK round-trip to ~1e-10. That tests the frame algebra.
* REAL hands do NOT. v12's FK places all five metacarpals IN the palm plane and
  forces abduction to zero at the PIP/DIP/IP hinges, so the palm arch and any
  hinge off-axis motion are unrepresentable by construction. A few millimetres
  of residual on real MediaPipe keypoints is the model, not a bug. Watch
  `off_axis` from `return_diagnostics=True` for the hinge part.
"""

import warnings

import numpy as np

import anatomical_angles_v12 as A12

# --------------------------------------------------------------------------
# Re-exports: import these from here so there is one obvious source
# --------------------------------------------------------------------------
ARTICULATION_ANGLES = list(A12.ARTICULATION_ANGLES)
FAN_ANGLE_NAMES = list(A12.FAN_ANGLE_NAMES)
ALL_V12_NAMES = list(A12.ALL_V12_NAMES)
BONES = list(A12.BONES)
WRIST = A12.WRIST
FINGER_CHAINS = dict(A12.FINGER_CHAINS)
MCP_IDS = dict(A12.MCP_IDS)
REF_BONE = A12.REF_BONE

N_ANGLES = len(ARTICULATION_ANGLES)          # 21
N_FAN = len(FAN_ANGLE_NAMES)                 # 4
ANGLE_INDEX = {n: i for i, n in enumerate(ARTICULATION_ANGLES)}

wrap_deg = A12.wrap_deg
unwrap_to_reference = A12.unwrap_to_reference
palm_frame = A12.palm_frame
bone_lengths_from_kps = A12.bone_lengths_from_kps

# --------------------------------------------------------------------------
# Bone naming: "Middle_MCP-PIP" <-> (9, 10)
# --------------------------------------------------------------------------
_JOINT_LABELS = {
    "Thumb": ("Wrist", "CMC", "MCP", "IP", "Tip"),
    "Index": ("Wrist", "MCP", "PIP", "DIP", "Tip"),
    "Middle": ("Wrist", "MCP", "PIP", "DIP", "Tip"),
    "Ring": ("Wrist", "MCP", "PIP", "DIP", "Tip"),
    "Pinky": ("Wrist", "MCP", "PIP", "DIP", "Tip"),
}

BONE_NAMES = []
BONE_NAME_TO_IDX = {}
IDX_TO_BONE_NAME = {}
for _finger, _chain in FINGER_CHAINS.items():
    _labels = _JOINT_LABELS[_finger]
    _ids = (WRIST,) + tuple(_chain)
    for _k in range(4):
        _name = f"{_finger}_{_labels[_k]}-{_labels[_k + 1]}"
        _pair = (_ids[_k], _ids[_k + 1])
        BONE_NAMES.append(_name)
        BONE_NAME_TO_IDX[_name] = _pair
        IDX_TO_BONE_NAME[_pair] = _name

assert [BONE_NAME_TO_IDX[n] for n in BONE_NAMES] == BONES, \
    "bone name order drifted from anatomical_angles_v12.BONES"


def _bone_key(k):
    """Coerce one bone key to the (parent_idx, child_idx) tuple FK wants."""
    if isinstance(k, str):
        if k in BONE_NAME_TO_IDX:
            return BONE_NAME_TO_IDX[k]
        cleaned = k.replace("(", "").replace(")", "").replace(",", "-")
        parts = [p for p in cleaned.split("-") if p.strip().isdigit()]
        if len(parts) == 2:
            return (int(parts[0]), int(parts[1]))
        raise KeyError(
            f"unrecognised bone name {k!r}; expected one of {BONE_NAMES[:3]}... "
            f"or an index pair")
    pair = tuple(int(i) for i in k)
    if len(pair) != 2:
        raise KeyError(f"bone key {k!r} is not a (parent, child) pair")
    return pair


def as_bone_dict(bone_lengths, scale=1.0, strict=True):
    """
    Anything -> {(parent_idx, child_idx): float}, the form FK requires.

    Accepts a dict keyed by "Middle_MCP-PIP" style names or by index pairs, or
    a length-20 sequence in `BONES` order. `scale` multiplies every value
    (use 1e-3 for mm -> m).
    """
    if isinstance(bone_lengths, dict):
        out = {_bone_key(k): float(v) * scale for k, v in bone_lengths.items()}
    else:
        arr = np.asarray(bone_lengths, dtype=np.float64).ravel()
        if arr.size != len(BONES):
            raise ValueError(
                f"expected {len(BONES)} bone lengths in BONES order, got {arr.size}")
        out = {b: float(v) * scale for b, v in zip(BONES, arr)}

    if strict:
        missing = [IDX_TO_BONE_NAME[b] for b in BONES if b not in out]
        if missing:
            raise KeyError(f"bone lengths missing {len(missing)}: {missing}")
        bad = [IDX_TO_BONE_NAME[b] for b in BONES
               if not np.isfinite(out[b]) or out[b] <= 0.0]
        if bad:
            raise ValueError(f"non-positive or non-finite bone lengths: {bad}")
    return out


def bone_dict_to_array(bone_lengths, scale=1.0):
    """Inverse convenience: -> (20,) array in `BONES` order."""
    d = as_bone_dict(bone_lengths, scale=scale)
    return np.array([d[b] for b in BONES], dtype=np.float64)


# --------------------------------------------------------------------------
# Angle dict <-> array
# --------------------------------------------------------------------------
def as_angle_dict(angles):
    """
    (21,) or (25,) array, or a dict, -> dict keyed by v12 names.
    A (21,) array is read in `ARTICULATION_ANGLES` order and carries no fan.
    """
    if isinstance(angles, dict):
        missing = [n for n in ARTICULATION_ANGLES if n not in angles]
        if missing:
            raise KeyError(f"angle dict missing {len(missing)}: {missing}")
        return dict(angles)

    arr = np.asarray(angles, dtype=np.float64).ravel()
    if arr.size == N_ANGLES:
        return dict(zip(ARTICULATION_ANGLES, arr.tolist()))
    if arr.size == N_ANGLES + N_FAN:
        return dict(zip(ALL_V12_NAMES, arr.tolist()))
    raise ValueError(
        f"expected {N_ANGLES} articulation angles (or {N_ANGLES + N_FAN} with "
        f"fan), got {arr.size}")


def as_fan_dict(fan_angles, check_order=True):
    """
    (4,) array or dict -> dict keyed by `FAN_ANGLE_NAMES`. None passes through.

    Values are WRAPPED into (-180, 180] first. A fan angle is a difference of
    two azimuths, so an unwrapped -328 deg is the same direction as +32 deg --
    but FK would swing the finger the long way round and build a garbage
    skeleton. This has been observed for real (`Pinky -328.0` in a left-hand
    `extract_palm_dirs.py` run), so it is wrapped here, not assumed away.

    `check_order` then warns if the implied azimuths are not in radial order
    (thumb > index > middle > ring > pinky). Out-of-order fans make the five
    metacarpals cross, which flips the sign of the SVD palm normal in
    `palm_frame` and mirrors every angle downstream.
    """
    if fan_angles is None:
        return None
    if isinstance(fan_angles, dict):
        missing = [n for n in FAN_ANGLE_NAMES if n not in fan_angles]
        if missing:
            raise KeyError(f"fan dict missing: {missing}")
        vals = [float(fan_angles[n]) for n in FAN_ANGLE_NAMES]
    else:
        arr = np.asarray(fan_angles, dtype=np.float64).ravel()
        if arr.size != N_FAN:
            raise ValueError(f"expected {N_FAN} fan angles, got {arr.size}")
        vals = arr.tolist()

    out = {n: float(wrap_deg(v)) for n, v in zip(FAN_ANGLE_NAMES, vals)}
    if check_order:
        az = fan_azimuths(out)
        order = [az[f] for f in ("Thumb", "Index", "Middle", "Ring", "Pinky")]
        if any(b >= a for a, b in zip(order, order[1:])):
            warnings.warn(
                "fan angles are not in radial order "
                + ", ".join(f"{f}={az[f]:+.1f}" for f in
                            ("Thumb", "Index", "Middle", "Ring", "Pinky"))
                + " -- metacarpals cross, which flips the palm normal and "
                  "mirrors every angle. Check for an unwrapped azimuth.",
                RuntimeWarning, stacklevel=2)
    return out


def fan_azimuths(fan_angles):
    """Fan angles -> per-finger azimuth in the palm plane, Middle = 0 deg.
    Mirrors the accumulation inside `forward_kinematics_v12`."""
    f = fan_angles if isinstance(fan_angles, dict) else dict(
        zip(FAN_ANGLE_NAMES, np.asarray(fan_angles, float).ravel().tolist()))
    az = {"Middle": 0.0}
    az["Index"] = az["Middle"] + float(f["Index_Middle_Fan"])
    az["Ring"] = az["Middle"] - float(f["Middle_Ring_Fan"])
    az["Pinky"] = az["Ring"] - float(f["Ring_Pinky_Fan"])
    az["Thumb"] = az["Index"] + float(f["Thumb_Index_Fan"])
    return az


def angles_to_array(angle_dict, names=None):
    names = ARTICULATION_ANGLES if names is None else names
    return np.array([float(angle_dict[n]) for n in names], dtype=np.float64)


# --------------------------------------------------------------------------
# The two functions the EKF actually calls
# --------------------------------------------------------------------------
def compute_angles(kps, hand="right", degrees=True,
                   return_fan=False, return_diagnostics=False):
    """
    (21,3) keypoints -> (21,) articulation angles, in `ARTICULATION_ANGLES`
    order. Scale- rotation- and translation-invariant, so GT and MediaPipe
    world landmarks need no alignment.

    return_fan=True         also returns the (4,) fan vector.
    return_diagnostics=True also returns the hinge off-axis dict, which is a
                            free per-frame measure of how badly the hinge model
                            is being violated -- useful for gating the EKF.
    """
    res = A12.compute_angles_v12(kps, hand=hand, degrees=degrees,
                                 return_diagnostics=return_diagnostics)
    d, diag = res if return_diagnostics else (res, None)

    art = angles_to_array(d)
    extras = []
    if return_fan:
        extras.append(angles_to_array(d, FAN_ANGLE_NAMES))
    if return_diagnostics:
        extras.append(diag)
    return (art, *extras) if extras else art


def compute_fan(kps, hand="right", degrees=True):
    """The 4 fan angles alone -- measure once per subject, then store."""
    d = A12.compute_angles_v12(kps, hand=hand, degrees=degrees)
    return angles_to_array(d, FAN_ANGLE_NAMES)


def compute_angles_dict(kps, hand="right", degrees=True):
    """All 25 named angles, unmodified from v12."""
    return A12.compute_angles_v12(kps, hand=hand, degrees=degrees)


def forward_kinematics(angles, bone_lengths, fan_angles=None, palm=None,
                       wrist_origin=None, degrees=True, scale=1.0):
    """
    Angles (+ calibrated fan + calibrated bone lengths) -> (21,3) keypoints.
    This is the EKF's block-2 measurement function.

    `angles` may be a (21,) array, a (25,) array, or a dict.
    `bone_lengths` may be name-keyed, index-keyed, or a (20,) array; `scale`
    converts units (1e-3 for mm -> m).
    Raises rather than defaulting the fan to zero.
    """
    ang = as_angle_dict(angles)
    fan = as_fan_dict(fan_angles)
    if fan is None:
        missing = [n for n in FAN_ANGLE_NAMES if n not in ang]
        if missing:
            raise KeyError(
                "no fan angles: pass fan_angles= (calibrated, preferred) or "
                f"include {missing} in `angles`. Refusing to reconstruct with "
                "zero finger spread.")
    return A12.forward_kinematics_v12(
        ang, as_bone_dict(bone_lengths, scale=scale), palm=palm,
        degrees=degrees, wrist_origin=wrist_origin, fan_angles=fan)


def round_trip(kps, hand="right"):
    """
    kps -> angles -> kps, in the source hand's own palm frame and origin.
    Returns (mean per-joint position error, reconstructed kps).
    Residual on real hands is palm arch + hinge violation, not numerical error.
    """
    return A12.round_trip_error(kps, hand=hand)


