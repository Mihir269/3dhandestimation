# Fixtures below are the right-hand calibration (calib_filled_tilt35) --
# present so the self-test exercises a REAL hand shape, not for use as data.
_SAMPLE_BONES_MM = {
    "Thumb_Wrist-CMC": 45.60, "Thumb_CMC-MCP": 35.75,
    "Thumb_MCP-IP": 33.50, "Thumb_IP-Tip": 26.15,
    "Index_Wrist-MCP": 91.24, "Index_MCP-PIP": 46.08,
    "Index_PIP-DIP": 26.84, "Index_DIP-Tip": 21.93,
    "Middle_Wrist-MCP": 87.40, "Middle_MCP-PIP": 49.38,
    "Middle_PIP-DIP": 30.75, "Middle_DIP-Tip": 23.80,
    "Ring_Wrist-MCP": 83.37, "Ring_MCP-PIP": 45.20,
    "Ring_PIP-DIP": 28.82, "Ring_DIP-Tip": 22.24,
    "Pinky_Wrist-MCP": 80.04, "Pinky_MCP-PIP": 35.48,
    "Pinky_PIP-DIP": 22.50, "Pinky_DIP-Tip": 19.19,
}
# from palm_dirs.json fan_deg: Thumb 67.8, Index 18.4, Middle 0, Ring -15.0, Pinky -30.5
_SAMPLE_FAN_DEG = {
    "Thumb_Index_Fan": 49.4, "Index_Middle_Fan": 18.4,
    "Middle_Ring_Fan": 15.0, "Ring_Pinky_Fan": 15.5,
}


def _selftest():
    rng = np.random.default_rng(0)
    ok = True

    print("hand_angles_v2 -> anatomical_angles_v12")
    print(f"  articulation   {N_ANGLES}: {ARTICULATION_ANGLES[0]} ... "
          f"{ARTICULATION_ANGLES[-1]}")
    print(f"  fan            {N_FAN} (calibration, not state)")
    print(f"  bones          {len(BONES)}: Middle_MCP-PIP -> "
          f"{BONE_NAME_TO_IDX['Middle_MCP-PIP']}")
    print(f"  thumb MCP abd  "
          f"{'ON' if 'Thumb_MCP_Abd' in ARTICULATION_ANGLES else 'OFF'}")
    print()

    bl = as_bone_dict(_SAMPLE_BONES_MM, scale=1e-3)      # mm -> m, real hand

    # 1 --- angle recovery over 500 random poses on a real hand shape -------
    worst_ang, worst_pos = 0.0, 0.0
    truth = None
    for _ in range(500):
        truth = dict(_SAMPLE_FAN_DEG)
        for n in ARTICULATION_ANGLES:
            truth[n] = float(rng.uniform(-10, 90) if n.endswith("_Flex")
                             else rng.uniform(-20, 20))
        kps = forward_kinematics(truth, bl)
        got = compute_angles_dict(kps)
        worst_ang = max(worst_ang, max(abs(float(wrap_deg(got[n] - truth[n])))
                                       for n in ALL_V12_NAMES))
        worst_pos = max(worst_pos, round_trip(kps)[0])
    print(f"  [1] angle recovery, 500 poses     worst {worst_ang:.3e} deg")
    print(f"      FK round-trip position        worst {worst_pos:.3e} m")
    ok &= worst_ang < 1e-6 and worst_pos < 1e-9

    # 2 --- the (21,) array path the EKF actually uses ----------------------
    kps = forward_kinematics(truth, bl)
    art, fan = compute_angles(kps, return_fan=True)
    rec = forward_kinematics(art, bl, fan_angles=fan,
                             palm=palm_frame(kps), wrist_origin=kps[WRIST])
    d_arr = float(np.max(np.linalg.norm(rec - kps, axis=1)))
    print(f"  [2] array path (21,) + fan (4,)   max joint err {d_arr:.3e} m")
    ok &= art.shape == (N_ANGLES,) and fan.shape == (N_FAN,) and d_arr < 1e-9

    # 3 --- name-keyed mm bones == index-keyed m bones ----------------------
    rec_mm = forward_kinematics(art, _SAMPLE_BONES_MM, fan_angles=fan,
                                scale=1e-3, palm=palm_frame(kps),
                                wrist_origin=kps[WRIST])
    d_mm = float(np.max(np.linalg.norm(rec_mm - rec, axis=1)))
    print(f"  [3] calib names + mm, scale=1e-3  max diff {d_mm:.3e} m")
    ok &= d_mm < 1e-12

    # 4 --- refuses to invent a fan -----------------------------------------
    try:
        forward_kinematics(art, bl)
        print("  [4] missing fan                   NOT RAISED  <-- BAD")
        ok = False
    except KeyError:
        print("  [4] missing fan angles            raises, good")

    # 5 --- the -328 deg wrap, caught and corrected -------------------------
    wrapped = dict(_SAMPLE_FAN_DEG)
    wrapped["Ring_Pinky_Fan"] = _SAMPLE_FAN_DEG["Ring_Pinky_Fan"] - 360.0
    fixed = as_fan_dict(wrapped)["Ring_Pinky_Fan"]
    print(f"  [5] fan {wrapped['Ring_Pinky_Fan']:+.1f} deg wrapped to "
          f"{fixed:+.1f} deg")
    ok &= abs(fixed - _SAMPLE_FAN_DEG["Ring_Pinky_Fan"]) < 1e-9

    # 6 --- crossed metacarpals warn instead of silently mirroring ----------
    crossed = dict(_SAMPLE_FAN_DEG)
    crossed["Index_Middle_Fan"] = -40.0
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        as_fan_dict(crossed)
    print(f"  [6] crossed metacarpals           "
          f"{'warns, good' if caught else 'SILENT  <-- BAD'}")
    ok &= bool(caught)

    # 7 --- wrap_deg on the Thumb_IP_Flex branch cut ------------------------
    w = float(wrap_deg(160.7 - -177.9))
    print(f"  [7] wrap_deg(160.7 - -177.9)      {w:+.1f} deg")
    ok &= abs(w + 21.4) < 1e-9

    # 8 --- a REAL hand does NOT round-trip exactly -------------------------
    noisy = kps + rng.normal(0.0, 0.002, kps.shape)
    err_noisy = round_trip(noisy)[0]
    _, diag = compute_angles(noisy, return_diagnostics=True)
    off = max(abs(v) for v in diag.values()) if diag else 0.0
    print(f"  [8] perturbed hand round-trip     {err_noisy * 1000:.2f} mm "
          f"(worst hinge off-axis {off:.1f} deg)")
    print("      ^ expected non-zero: palm arch and hinge abduction are not")
    print("        representable. Only FK-built poses close to 1e-10.")

    print()
    print("SELF-TEST PASSED" if ok else "SELF-TEST FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(_selftest())
